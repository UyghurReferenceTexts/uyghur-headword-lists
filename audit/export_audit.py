"""
export_audit.py -- export the Gemini audit verdicts and the printed-error lists
from the dictionary workbooks into two TSV files for publication.

    python export_audit.py --src E:\\uyghur_library\\dictionaries --out audit

Reads, from every workbook listed in WORKS:

    Processed               -> audit/gemini_audit.tsv
    print_error(s), if any  -> audit/print_errors.tsv

and prints a per-dictionary check of the benchmark figures (Gemini findings,
accept / reject only), so the numbers can be compared with the root README
before anything is uploaded.

Nothing is written back to the workbooks; they are opened read-only.

Options
    --src DIR       folder holding the .xlsx workbooks        (default: .)
    --out DIR       folder to write the TSVs into             (default: audit)
    --drop-notes    leave the free-text `note` and `applied` columns empty
    --dry-run       report counts, write nothing
"""

import argparse
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

import openpyxl

# Workbook -> dictionary label, in the order rows are written.
WORKS = [
    ("imla_lughiti_2009.xlsx", "imla_lughiti_2009"),
    *[(f"izahliq_lughet_1990s_v{i}.xlsx", f"izahliq_lughet_1990s_v{i}") for i in range(1, 7)],
    ("izahliq_lughet_2011_v1.xlsx", "izahliq_lughet_2011_v1"),
    ("izahliq_lughet_2011_v2.xlsx", "izahliq_lughet_2011_v2"),
]

AUDIT_COLUMNS = [
    "dictionary", "image", "row_id", "issue", "field", "excel_text",
    "image_text", "explanation", "confidence", "decision", "finder",
    "attestation_class", "note", "applied",
]

PRINT_COLUMNS = ["dictionary", "row_id", "printed_form", "correct_form",
                 "source_page", "note"]

# Processed-sheet header -> output column. The three works were audited with
# slightly different scripts, so the same idea sits under different names.
HEADER_MAP = {
    "image": "image",
    "row_id": "row_id",
    "issue": "issue",
    "field": "field",
    "excel_text": "excel_text",
    "image_text": "image_text",
    "explanation": "explanation",
    "confidence": "confidence",
    "accept/reject": "decision",
    "finder": "finder",
    "attestation class": "attestation_class",   # 1990s v1-v5
    "note": "note",                             # 1990s
    "auto-scan note": "note",                   # 2009, 2011
    "applied action": "applied",                # 1990s
    "apply status": "applied",                  # 2011
}

PRINT_HEADER_MAP = {
    "row_uid": "row_id",
    "headword print error": "printed_form",
    "correct form": "correct_form",
    "source column": "source_page",
    "note": "note",
}

# 2009: these rows were generated by a script, not proposed by Gemini, and
# the 2009 sheet has no Finder column to say so.
SCRIPT_ISSUES = {"parenthetical stray (generated)"}

# INDEX('Sheet'!$B:$B,MATCH(TRIM(A2),'Sheet'!$A:$A,0)) -- the only formula
# shape the print_error sheets use.
INDEX_MATCH = re.compile(
    r"INDEX\('(?P<sheet>[^']+)'!\$(?P<col>[A-Z]+):\$[A-Z]+,\s*"
    r"MATCH\(TRIM\((?P<key>[A-Z]+)\d+\),'(?P=sheet)'!\$(?P<keycol>[A-Z]+):",
)

replaced_whitespace = 0


def clean(value):
    """Cell -> one-line string. Tabs and line breaks would break the TSV."""
    global replaced_whitespace
    if value is None:
        return ""
    text = str(value).strip()
    if any(ch in text for ch in "\t\r\n"):
        replaced_whitespace += 1
        text = re.sub(r"[\t\r\n]+", " ", text)
    return text


def norm_header(h):
    return str(h).strip().lower() if h is not None else ""


def norm_decision(value):
    text = clean(value).lower()
    return "" if text in ("", "none") else text


def norm_finder(raw, issue, label):
    text = clean(raw).lower()
    if text.startswith("gemini"):
        return "gemini"
    if text.startswith("claude"):
        return "claude"
    if text:
        return text
    # No Finder column: 2009 and 2011 were Gemini-only, apart from the
    # script-generated 2009 rows.
    if issue in SCRIPT_ISSUES:
        return "script"
    return "gemini"


def data_rows(ws):
    rows = list(ws.iter_rows(values_only=True))
    if not rows:
        return [], []
    return rows[0], [r for r in rows[1:] if any(c not in (None, "") for c in r)]


def export_processed(path, label, drop_notes):
    wb = openpyxl.load_workbook(path, read_only=True, data_only=True)
    if "Processed" not in wb.sheetnames:
        sys.exit(f"  ! {path.name}: no 'Processed' sheet")
    header, rows = data_rows(wb["Processed"])
    where = {}
    for i, h in enumerate(header):
        out = HEADER_MAP.get(norm_header(h))
        if out and out not in where:
            where[out] = i
    missing = [c for c in ("row_id", "issue", "decision") if c not in where]
    if missing:
        sys.exit(f"  ! {path.name}: Processed sheet lacks {missing}")

    out = []
    for r in rows:
        get = lambda col: r[where[col]] if col in where and where[col] < len(r) else None
        rec = {c: clean(get(c)) for c in AUDIT_COLUMNS if c in where}
        rec["dictionary"] = label
        rec["decision"] = norm_decision(get("decision"))
        rec["finder"] = norm_finder(get("finder"), rec["issue"], label)
        if drop_notes:
            rec["note"] = rec["applied"] = ""
        out.append([rec.get(c, "") for c in AUDIT_COLUMNS])
    wb.close()
    return out


def resolve(formula, row_values, wb, cache):
    """Evaluate the INDEX/MATCH shape used in the print_error sheets."""
    m = INDEX_MATCH.search(formula)
    if not m:
        return None
    sheet, col, keycol = m["sheet"], m["col"], m["keycol"]
    key_col_idx = openpyxl.utils.column_index_from_string(m["key"]) - 1
    key = clean(row_values[key_col_idx])
    if sheet not in cache:
        if sheet not in wb.sheetnames:
            return None
        table = {}
        kc = openpyxl.utils.column_index_from_string(keycol) - 1
        for r in wb[sheet].iter_rows(values_only=True):
            if r and kc < len(r) and r[kc] is not None:
                table[clean(r[kc])] = r
        cache[sheet] = table
    row = cache[sheet].get(key)
    if row is None:
        return None
    vc = openpyxl.utils.column_index_from_string(col) - 1
    return row[vc] if vc < len(row) else None


def export_print_errors(path, label):
    formulas = openpyxl.load_workbook(path, read_only=True)
    names = [s for s in formulas.sheetnames if s.lower().startswith("print_error")]
    if not names:
        formulas.close()
        return [], 0
    values = openpyxl.load_workbook(path, read_only=True, data_only=True)
    f_header, f_rows = data_rows(formulas[names[0]])
    v_rows = [r for r in values[names[0]].iter_rows(values_only=True, min_row=2)
              if any(c not in (None, "") for c in r)]
    where = {PRINT_HEADER_MAP[norm_header(h)]: i for i, h in enumerate(f_header)
             if norm_header(h) in PRINT_HEADER_MAP}

    out, unresolved, cache = [], 0, {}
    for f_row, v_row in zip(f_rows, v_rows):
        rec = {"dictionary": label}
        for col, i in where.items():
            raw_f = f_row[i] if i < len(f_row) else None
            raw_v = v_row[i] if i < len(v_row) else None
            if isinstance(raw_f, str) and raw_f.startswith("="):
                # Cached value if Excel saved one, else evaluate it ourselves.
                if raw_v in (None, "") or str(raw_v) == "row_id not found":
                    raw_v = resolve(raw_f, f_row, values, cache)
                    if raw_v is None:
                        unresolved += 1
            rec[col] = clean(raw_v)
        out.append([rec.get(c, "") for c in PRINT_COLUMNS])
    formulas.close()
    values.close()
    return out, unresolved


def write_tsv(path, columns, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as f:
        f.write("\t".join(columns) + "\n")
        for r in rows:
            f.write("\t".join(r) + "\n")


def sort_key(order):
    # Dictionary order first, then row_id; ties keep sheet order (stable sort).
    return lambda r: (order[r[0]], r[2] if len(r) > 2 else "")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default=".")
    ap.add_argument("--out", default="audit")
    ap.add_argument("--drop-notes", action="store_true")
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    src, out_dir = Path(a.src), Path(a.out)

    order = {label: i for i, (_, label) in enumerate(WORKS)}
    audit, printed = [], []
    total_unresolved = 0

    print(f"\n  {'dictionary':26s} {'rows':>6} {'gemini':>7} {'accepted':>9} "
          f"{'precision':>9}  print errors")
    for name, label in WORKS:
        path = src / name
        if not path.exists():
            print(f"  ! missing {path}")
            continue
        rows = export_processed(path, label, a.drop_notes)
        perr, unresolved = export_print_errors(path, label)
        total_unresolved += unresolved
        audit.extend(rows)
        printed.extend(perr)

        dec_i, fin_i = AUDIT_COLUMNS.index("decision"), AUDIT_COLUMNS.index("finder")
        judged = [r for r in rows if r[fin_i] == "gemini" and r[dec_i] in ("accept", "reject")]
        acc = sum(r[dec_i] == "accept" for r in judged)
        prec = f"{100 * acc / len(judged):.1f}%" if judged else "-"
        print(f"  {label:26s} {len(rows):>6,} {len(judged):>7,} {acc:>9,} {prec:>9}"
              f"  {len(perr) or ''}")

    audit.sort(key=sort_key(order))
    printed.sort(key=lambda r: (order[r[0]], r[1]))

    dec_i, fin_i = AUDIT_COLUMNS.index("decision"), AUDIT_COLUMNS.index("finder")
    judged = [r for r in audit if r[fin_i] == "gemini" and r[dec_i] in ("accept", "reject")]
    acc = sum(r[dec_i] == "accept" for r in judged)
    print(f"  {'total':26s} {len(audit):>6,} {len(judged):>7,} {acc:>9,} "
          f"{100 * acc / len(judged):>8.1f}%  {len(printed)}")

    other = Counter(r[dec_i] for r in audit if r[dec_i] not in ("accept", "reject"))
    if other:
        print("\n  decisions other than accept/reject (kept, not counted):")
        for d, n in other.most_common():
            print(f"      {n:>5}  {d or '(empty)'}")
    finders = Counter(r[fin_i] for r in audit)
    print(f"\n  finders: {dict(finders)}")
    if replaced_whitespace:
        print(f"  {replaced_whitespace} cell(s) had tabs or line breaks, joined with spaces")
    if total_unresolved:
        print(f"  ! {total_unresolved} print-error formula cell(s) could not be "
              f"resolved and were left empty -- open those sheets and check")

    if a.dry_run:
        print("\n  dry run: nothing written")
        return
    write_tsv(out_dir / "gemini_audit.tsv", AUDIT_COLUMNS, audit)
    write_tsv(out_dir / "print_errors.tsv", PRINT_COLUMNS, printed)
    print(f"\n  -> {out_dir / 'gemini_audit.tsv'}  ({len(audit):,} rows)")
    print(f"  -> {out_dir / 'print_errors.tsv'}  ({len(printed):,} rows)")


if __name__ == "__main__":
    main()
